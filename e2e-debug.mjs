import { chromium } from 'file:///C:/Users/linch/.workbuddy/binaries/node/workspace/node_modules/playwright-core/index.mjs'
const exe = 'C:/Users/linch/AppData/Local/ms-playwright/chromium-1244/chrome-win64/chrome.exe'
const browser = await chromium.launch({ executablePath: exe, headless: true })
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } })
page.on('console', m => console.log('[console]', m.type(), m.text()))
page.on('pageerror', e => console.log('[pageerror]', e.message))
page.on('requestfailed', r => console.log('[reqfail]', r.url(), r.failure()?.errorText))
await page.goto('http://127.0.0.1:8799//settings', { waitUntil: 'domcontentloaded' })
await page.waitForTimeout(4000)
console.log('URL:', page.url())
console.log('title:', await page.title())
const html = await page.evaluate(() => document.body.innerText.slice(0, 400))
console.log('body text:', html)
const rails = await page.evaluate(() => [...document.querySelectorAll('[class*=rail]')].map(e => e.className).slice(0, 10))
console.log('rail classes:', JSON.stringify(rails))
await page.screenshot({ path: 'D:/xkx/xkx_appproj/happy_中转站/e2e-debug.png' })
await browser.close()
